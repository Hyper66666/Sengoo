    pub fn with_ffi(ffi: FfiCodegenConfig) -> Self {

        let mut cg = Self {

            ir: String::new(),

            indent: 0,

            declarations: String::new(),

            ffi,

            strings: Vec::new(),

            string_counter: 0,

            name_cache: Vec::new(),

            type_str_cache: HashMap::new(),

            load_counter: 0,

        };

        cg.emit_header();

        cg.declare_runtime_functions();

        cg

    }



    fn emit_header(&mut self) {

        // target triple 鏀惧湪 declarations 鏈€鍓嶉潰锛岀‘淇濆畠锟?IR 鐨勭涓€锟?
        self.declarations.push_str("; Sengoo LLVM IR\n");

        self.declarations

            .push_str("; Generated by Sengoo Compiler\n\n");



        // 璁剧疆 target triple 閬垮厤 clang 锟?-Woverride-module 璀﹀憡

        if cfg!(target_os = "windows") {

            self.declarations

                .push_str("target triple = \"x86_64-pc-windows-msvc\"\n\n");

        } else if cfg!(target_os = "macos") {

            self.declarations

                .push_str("target triple = \"x86_64-apple-macosx\"\n\n");

        } else {

            self.declarations

                .push_str("target triple = \"x86_64-unknown-linux-gnu\"\n\n");

        }

    }



    /// 澹版槑杩愯鏃跺嚱鏁帮紙澶栭儴 C 鍑芥暟锟?
