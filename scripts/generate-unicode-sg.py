#!/usr/bin/env python3
"""Regenerate pure Sengoo Unicode 17 property trees from pinned local data.

No network access occurs here or during a compiler build. --check verifies the
committed generated module. Unicode data and license are kept with the inputs.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/stdlib/unicode-data/17.0.0"
OUTPUT = ROOT / "tools/stdlib/unicode_tables.sg"
PINNED = {
    "GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "GraphemeBreakTest.txt": "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    "emoji-data.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    "EastAsianWidth.txt": "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33",
    "LICENSE.txt": "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96",
}


def records(name):
    for line in (DATA / name).read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        fields = [s.strip() for s in body.split(";")]
        span = fields[0].split("..")
        lo, hi = int(span[0], 16), int(span[-1], 16)
        yield lo, hi, fields[1:]


def merged(rows):
    result = []
    for lo, hi, value in sorted(rows):
        if result and lo <= result[-1][1]:
            raise ValueError("overlapping Unicode intervals")
        if result and lo == result[-1][1] + 1 and value == result[-1][2]:
            result[-1] = result[-1][0], hi, value
        else:
            result.append((lo, hi, value))
    return result


def tree(rows, indent="    "):
    if not rows:
        return "0"
    middle = len(rows) // 2
    lo, hi, value = rows[middle]
    left = tree(rows[:middle], indent + "    ")
    right = tree(rows[middle + 1:], indent + "    ")
    return (f"if cp < {lo} {{\n{indent}    {left}\n{indent}}} else {{\n"
            f"{indent}    if cp <= {hi} {{ {value} }} else {{\n{indent}    {right}\n{indent}    }}\n{indent}}}")


def generate():
    for name, expected in PINNED.items():
        actual = hashlib.sha256((DATA / name).read_bytes()).hexdigest()
        if actual != expected:
            raise ValueError(f"Unicode input checksum mismatch: {name}: {actual}")
    classes = {"CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5,
               "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8,
               "L": 9, "V": 10, "T": 11}
    functions = {
        "unicode_gcb_data": [(lo, hi, classes[f[0]]) for lo, hi, f in records("GraphemeBreakProperty.txt") if f[0] in classes],
        "unicode_incb_data": [(lo, hi, {"Consonant": 1, "Linker": 2, "Extend": 3}[f[1]]) for lo, hi, f in records("DerivedCoreProperties.txt") if f[0] == "InCB"],
        "unicode_pictographic_data": [(lo, hi, 1) for lo, hi, f in records("emoji-data.txt") if f[0] == "Extended_Pictographic"],
        "unicode_emoji_presentation_data": [(lo, hi, 1) for lo, hi, f in records("emoji-data.txt") if f[0] == "Emoji_Presentation"],
        "unicode_ignorable_data": [(lo, hi, 1) for lo, hi, f in records("DerivedCoreProperties.txt") if f[0] == "Default_Ignorable_Code_Point"],
        "unicode_wide_data": [(lo, hi, 1) for lo, hi, f in records("EastAsianWidth.txt") if f[0] in ("W", "F")],
    }
    lines = ["// Generated by scripts/generate-unicode-sg.py. Unicode 17.0.0.",
             "// Property trees only; grapheme and terminal policy live in unicode.sg.",
             "// Inputs and Unicode license: tools/stdlib/unicode-data/17.0.0/.", ""]
    for name, rows in functions.items():
        rows = merged(rows)
        lines.append(f"// {len(rows)} disjoint intervals, logarithmic lookup.")
        lines.append(f"def {name}(cp: i64) -> i64 {{\n    {tree(rows)}\n}}\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("unicode_tables.sg differs; run scripts/generate-unicode-sg.py")
        print("Unicode input hashes and generated Sengoo property trees match")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(expected)} characters)")


if __name__ == "__main__":
    main()
